package io.github.hyjn.nexori.plugin.target.logic;

import io.github.hyjn.nexori.plugin.target.DestinationTargetDefinition;
import io.github.hyjn.nexori.plugin.target.DestinationTargetKind;

import javax.annotation.Nonnull;
import javax.annotation.Nullable;
import java.util.Locale;

public final class DestinationTargetDefaultPlanner {

    private DestinationTargetDefaultPlanner() {
    }

    @Nonnull
    public static String targetId(@Nonnull String worldName) {
        return worldName.toLowerCase(Locale.ROOT) + ".natural_spawn";
    }

    @Nonnull
    public static String displayName(@Nonnull String worldName) {
        String normalized = worldName.trim();
        if (normalized.isEmpty()) {
            return "Natural Spawn";
        }
        return normalized.substring(0, 1).toUpperCase(Locale.ROOT) + normalized.substring(1) + " Natural Spawn";
    }

    @Nonnull
    public static DestinationTargetDefinition buildDefinition(
        @Nonnull String worldName,
        @Nullable DestinationTargetDefinition existing
    ) {
        return new DestinationTargetDefinition(
            targetId(worldName),
            existing == null ? displayName(worldName) : existing.displayName(),
            DestinationTargetKind.NATURAL_SPAWN,
            worldName,
            "natural_spawn",
            existing == null ? "" : existing.arrivalMessage(),
            "{\"autoGenerated\":true}"
        );
    }
}
