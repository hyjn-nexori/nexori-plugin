package io.github.hyjn.nexori.plugin.target.logic;

import io.github.hyjn.nexori.plugin.target.DestinationTargetDefinition;
import io.github.hyjn.nexori.plugin.target.DestinationTargetKind;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;

final class DestinationTargetDefaultPlannerTest {

    @Test
    void targetIdUsesLowercaseWorldNameAndNaturalSpawnSuffix() {
        assertEquals("overworld.natural_spawn", DestinationTargetDefaultPlanner.targetId("overworld"));
        assertEquals("the_end.natural_spawn", DestinationTargetDefaultPlanner.targetId("The_End"));
        assertEquals("nether.natural_spawn", DestinationTargetDefaultPlanner.targetId("NETHER"));
    }

    @Test
    void displayNameCapitalizesFirstCharacterAndAddsNaturalSpawn() {
        assertEquals("Overworld Natural Spawn", DestinationTargetDefaultPlanner.displayName("overworld"));
        assertEquals("Nether Natural Spawn", DestinationTargetDefaultPlanner.displayName("nether"));
    }

    @Test
    void blankWorldNameDisplayNameDefaultsToNaturalSpawn() {
        assertEquals("Natural Spawn", DestinationTargetDefaultPlanner.displayName("   "),
            "Trimmed blank falls through to the empty-string guard returning 'Natural Spawn'");
        assertEquals("Natural Spawn", DestinationTargetDefaultPlanner.displayName(""));
    }

    @Test
    void buildsNaturalSpawnDefinitionWithMetadata() {
        DestinationTargetDefinition def = DestinationTargetDefaultPlanner.buildDefinition("overworld", null);

        assertEquals("overworld.natural_spawn", def.id());
        assertEquals("Overworld Natural Spawn", def.displayName());
        assertEquals(DestinationTargetKind.NATURAL_SPAWN, def.kind());
        assertEquals("overworld", def.worldName());
        assertEquals("natural_spawn", def.arrivalPointId());
        assertEquals("", def.arrivalMessage());
        assertEquals("{\"autoGenerated\":true}", def.metadataJson());
    }

    @Test
    void preservesExistingDisplayNameAndArrivalMessageWhenExistingPresent() {
        DestinationTargetDefinition existing = new DestinationTargetDefinition(
            "overworld.natural_spawn", "Custom Display", DestinationTargetKind.NATURAL_SPAWN,
            "overworld", "natural_spawn", "Welcome to Overworld!", "{}"
        );
        DestinationTargetDefinition def = DestinationTargetDefaultPlanner.buildDefinition("overworld", existing);

        assertEquals("Custom Display", def.displayName(),
            "When existing != null, displayName() uses existing.displayName()");
        assertEquals("Welcome to Overworld!", def.arrivalMessage(),
            "When existing != null, arrivalMessage uses existing.arrivalMessage()");
    }
}
